def add_compound_descriptors():
    try:
        from rdkit import Chem
        from rdkit.Chem import Descriptors, Lipinski, QED
    except Exception as exc:  # pragma: no cover
        print("RDKit unavailable, descriptors left as null:", exc)
        return
    for c in COMPOUNDS:
        c.setdefault("food_safe", False)
        c.setdefault("fluorescence", False)
        try:
            mol = Chem.MolFromSmiles(c["smiles"])
            if mol is None:
                raise ValueError("RDKit could not parse SMILES")
            c["descriptors"] = {
                "mw": round(Descriptors.MolWt(mol), 2),
                "logp": round(Descriptors.MolLogP(mol), 2),
                "tpsa": round(Descriptors.TPSA(mol), 2),
                "hbd": Lipinski.NumHDonors(mol),
                "hba": Lipinski.NumHAcceptors(mol),
                "rotatable_bonds": Lipinski.NumRotatableBonds(mol),
                "rings": mol.GetRingInfo().NumRings(),
                "heavy_atoms": mol.GetNumHeavyAtoms(),
                "qed": round(QED.qed(mol), 3) if hasattr(QED, "qed") else None,
                "formal_charge": Chem.GetFormalCharge(mol),
            }
        except Exception as exc:
            print(f"descriptor fallback for {c['id']}: {exc}")
            c["descriptors"] = {
                "mw": c.get("mw"), "logp": None, "tpsa": None, "hbd": None, "hba": None,
                "rotatable_bonds": None, "rings": None, "heavy_atoms": None, "qed": None,
                "formal_charge": None,
            }


def main():
    add_compound_descriptors()
    payloads = {
        "proteins.json": PROTEINS,
        "protectants.json": PROTECTANTS,
        "compounds.json": {
            "schema_version": "1.0",
            "curated_date": CURATED,
            "disclaimer": (
                "Curated demonstration compounds and formulation additives. Regulatory limits shown are indicative; "
                "always confirm the current local food-additive regulation and permitted use level."
            ),
            "items": COMPOUNDS,
        },
        "matrices.json": MATRICES,
        "spectra.json": SPECTRA,
    }
    for name, payload in payloads.items():
        out = DATA / name
        out.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(f"wrote {out} ({out.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
